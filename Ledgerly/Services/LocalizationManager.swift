import SwiftUI

@MainActor
final class LocalizationManager: ObservableObject {
    @Published var language: Language {
        didSet {
            UserDefaults.standard.set(language.rawValue, forKey: "app.language")
        }
    }

    init(language: Language = .current) {
        self.language = language
    }

    subscript(_ key: String) -> String {
        table[language]?[key] ?? table[.en]?[key] ?? key
    }

    nonisolated static func localized(_ key: String) -> String {
        let lang = Language.current
        return table[lang]?[key] ?? table[.en]?[key] ?? key
    }

    private static let table: [Language: [String: String]] = [
        .ru: ru,
        .en: en,
        .zhHans: zhHans
    ]

    nonisolated static func defaultBookName(_ name: String) -> String {
        for key in ["demo.dailyExpenses", "demo.familyLedger"] {
            if table.values.contains(where: { $0[key] == name }) { return localized(key) }
        }
        return name
    }

    nonisolated static func systemCategoryName(_ name: String) -> String {
        for translations in table.values {
            if let key = translations.first(where: { $0.key.hasPrefix("category.") && $0.value == name })?.key {
                return localized(key)
            }
        }
        return name
    }

    private var table: [Language: [String: String]] { Self.table }

